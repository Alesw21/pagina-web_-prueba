-- 01. Crear subservicios relacionados con cada tarjeta principal.
create table if not exists public.subservicios (
  id bigint generated by default as identity primary key,
  servicio_id bigint not null references public.servicios(id) on delete cascade,
  nombre text not null,
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  unique(servicio_id, nombre)
);

-- 02. Seguridad: la página solo puede leer opciones activas.
alter table public.subservicios enable row level security;
drop policy if exists "lectura_publica_subservicios_activos" on public.subservicios;
create policy "lectura_publica_subservicios_activos"
  on public.subservicios for select to anon, authenticated
  using (activo = true and exists (
    select 1 from public.servicios s where s.id = servicio_id and s.activo = true
  ));

