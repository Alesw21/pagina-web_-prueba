-- 1. TABLA: cada fila representa un servicio ofrecido.
create table if not exists public.servicios (
  id bigint generated by default as identity primary key,
  nombre text not null,             -- Título de la tarjeta
  categoria text not null,          -- Filtro: Soporte, Seguridad, Web, Redes
  descripcion text not null,        -- Texto corto bajo el título
  imagen_url text,                  -- URL https de Supabase Storage o de otro alojamiento
  destacado boolean not null default false,
  activo boolean not null default true, -- false = ocultar en la web
  creado_en timestamptz not null default now()
);

-- 2. SEGURIDAD: habilitar Row Level Security.
alter table public.servicios enable row level security;

-- 3. ACCESO PÚBLICO: visitantes solo pueden leer servicios activos.
-- Eliminar una política anterior con el mismo nombre permite repetir el script.
drop policy if exists "lectura_publica_servicios_activos" on public.servicios;
create policy "lectura_publica_servicios_activos"
  on public.servicios for select
  to anon, authenticated
  using (activo = true);

